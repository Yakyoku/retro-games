// ---------- 2D の解析 ----------
const OPEN2D = new Set(['=', '-', '|', '+', 'P', 'c', 'f']);
export function parse2D(st) {
  const rows = st.map.length, cols = st.map[0].length;
  const cell = (r, c) => st.map[r][c];
  const open = new Uint8Array(rows * cols);
  const h = new Uint8Array(rows * cols); // (r,c) と (r,c+1) がつながる
  const v = new Uint8Array(rows * cols); // (r,c) と (r+1,c) がつながる
  const enemies = []; const rocks = []; let start = null;
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
    const ch = cell(r, c); const i = r * cols + c;
    if (OPEN2D.has(ch)) open[i] = 1;
    if (ch === 'P') start = { r, c };
    if (ch === 'c' || ch === 'f') enemies.push({ type: ch === 'c' ? 'chaser' : 'fire', r, c });
    if (ch === 'R') rocks.push({ r, c });
  }
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
    const a = cell(r, c);
    if (!OPEN2D.has(a)) continue;
    if (c + 1 < cols) { const b = cell(r, c + 1); if (OPEN2D.has(b) && a !== '|' && b !== '|') h[r * cols + c] = 1; }
    if (r + 1 < rows) { const b = cell(r + 1, c); if (OPEN2D.has(b) && a !== '-' && b !== '-') v[r * cols + c] = 1; }
  }
  return { rows, cols, open, h, v, enemies, rocks, start };
}

// ---------- 3D の解析 ----------
export function parse3D(st) {
  const n = st.map.length, m = st.map[0].length;
  const solid = new Uint8Array(n * m); const support = new Uint8Array(n * m);
  const enemies = []; const rocks = []; let start = null;
  for (let z = 0; z < n; z++) for (let x = 0; x < m; x++) {
    const ch = st.map[z][x]; const i = z * m + x;
    if (ch === '#' || ch === 'S') solid[i] = 1;
    if (ch === 'S') support[i] = 1;
    if (ch === 'P') start = { x, z };
    if (ch === 'c' || ch === 'f') enemies.push({ type: ch === 'c' ? 'chaser' : 'fire', x, z });
    if (ch === 'R') rocks.push({ x, z });
  }
  // 岩ごとの支え（上下左右に隣り合う S）
  for (const r of rocks) {
    r.supports = [];
    for (const [dx, dz] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const x = r.x + dx, z = r.z + dz;
      if (x >= 0 && z >= 0 && x < m && z < n && support[z * m + x]) r.supports.push(z * m + x);
    }
  }
  return { w: m, h: n, solid, support, enemies, rocks, start };
}
