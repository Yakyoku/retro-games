function sporeCore(carrier) {
  const m = new ModelBuilder(2);
  m.f(ico(0.24, 1), carrier ? '#ff8a4a' : '#ff6aa8', [0, 0, 0], [0, 0, 0], 1, { r: 0.3, e: carrier ? '#ff5a1a' : '#ff2a7a', ei: 0.5 });
  for (let k = 0; k < 12; k++) {
    const u = hash(k, 1) * 2 - 1, a = hash(k, 2) * TAU, r = Math.sqrt(1 - u * u), d = [Math.cos(a) * r, u, Math.sin(a) * r];
    const q = new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 1, 0), new THREE.Vector3(...d)), e = new THREE.Euler().setFromQuaternion(q);
    m.f(cone(0.035, 0.24, 5), carrier ? '#ffd0a0' : '#ffc0dc', [d[0] * 0.32, d[1] * 0.32, d[2] * 0.32], [e.x, e.y, e.z], 1, { r: 0.3 });
    m.e(sph(0.03, 5, 4), carrier ? '#ffe08a' : '#ffffff', [d[0] * 0.45, d[1] * 0.45, d[2] * 0.45], [0, 0, 0], 1, 2);
  }
  return m.build();
}
