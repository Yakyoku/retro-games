const PI = Math.PI, TAU = PI * 2;
const hash = (i, s = 0) => { const v = Math.sin(i * 127.1 + s * 311.7) * 43758.5453; return v - Math.floor(v); };
// 水平の翼（平面形 [x, 張り出し] を厚み t で。y の位置に置く）
function wing(m, plan, t, col, y, o, bevel = 0.012) {
  m.m(extrude(plan, t, bevel), col, [0, y, 0], [PI / 2, 0, 0], 1, o);
}

// ---- 自機 ORBITAL WING: 鋭い機首・後退翼・双垂直尾翼・2 基の噴射口 --------------------------
