// ORBITAL WINGS — モダン音源の効果音（すべてこの作品のために作ったもの。既存のゲームの音はまねていない）
//
// 1 つの効果音 = 層（layer）の重ね合わせ。層は 1 つの発振器＋フィルター＋音量の山。
//   { t: 始まる時刻(秒), type: 'sine'|'tri'|'saw'|'pulse'|'noise'|'fm'|'dust'（破片）|'metal'（金属）,
//     f: [始めの高さ Hz, 終わりの高さ, かかる秒数], a: 立ち上がり, h: 保つ, d: 消えるまで（-60dB）, g: 音量,
//     fm: [変調の周波数比, 始めの深さ, 終わりの深さ, 秒], flt: ['lp'|'bp'|'hp', 始め Hz, 終わり Hz, 秒, 鋭さ 0-1],
//     pan, rev（残響へ）, dly（ディレイへ）, vib: [Hz, セント], am: [Hz, 深さ], det: 層ごとのばらつき（セント）, fix: 高さを変えない }
// 効果音ごと: pri（優先度）, gain, poly（同じ音を重ねてよい数。既定 1 = 重ねない）, vary（毎回の高さのばらつき セント）,
//   gvar（音量のばらつき）, rr（順番に使う高さのずれ セント）, steps（step ごとの半音）, duck: [曲を下げる量, 秒], gap（最短の間隔 秒）, ui
//
// ■ オプションの弾の決まり（従来どおり）
//   'option_shot' という音は無い。オプションが何機いても 1 回の斉射につき shot / double / laser を 1 回だけ鳴らす。
//   音源側でも、同じ名前を同じフレームに何度呼んでも 1 回分、同じ名前は重ならない（poly 1）。

const hz = (m) => 440 * Math.pow(2, (m - 69) / 12);
// 音を順に鳴らす: list = [[MIDI 番号, 長さ秒, 音量倍率]...]
function notes(type, list, o = {}) {
  const out = []; let t = o.t ?? 0;
  for (const [m, dur, k = 1] of list) {
    if (m != null) out.push({ ...o, t, type, f: [hz(m) * (o.bend ?? 1), hz(m), 0.02], a: o.a ?? 0.002, h: dur * (o.hold ?? 0.5), d: o.d ?? dur * 1.2 + 0.05, g: (o.g ?? 0.3) * k });
    t += dur;
  }
  return out;
}
// 爆発: 低い胴鳴り＋爆風（左右に少し広げる）＋破片。s = 0 小 … 3 特大
